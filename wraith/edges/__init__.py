"""Edge engine — the attacker-direction capability graph (frozen schema §4).

Module 4 (the Membership Resolver) is the first writer here: it resolves group
membership into direct ``MemberOf`` edges (stored ``member`` links + implicit
primary-group + a minimal synthetic special-identity set) and materializes their
transitive ``effective_membership`` closure. Later modules add ACL/UAC/DCSync/
trust/GPO/ADCS edge kinds into the same ``edge`` table.

The membership resolver reuses BloodHound's MemberOf *idea* (member->group,
traversable, nesting transitive) implemented natively for the offline case; no
foreign code is copied. Determinism, counted gaps, and provenance-on-every-edge
are preserved.
"""

